const FingerBrailleSVG: FC<FingerBrailleSVGProps> = ({ brailleDots = [] }) => {
  // Set for quick lookup
  const dotSet = new Set(brailleDots);
  
  // 1. 左手と右手のSVGを分割
  // 型述語 (d is 1 | 2 | 3)を使うことで、leftDotsは (1 | 2 | 3)[] と推論される
  // 実行時ロジックに基づいて型の絞り込みを行い、型の安全性を高める
  const leftDots = brailleDots.filter((d): d is 1 | 2 | 3 => d === 1 || d === 2 || d === 3);
  const rightDots = brailleDots.filter((d): d is 4 | 5 | 6 => d === 4 || d === 5 || d === 6);

  // 2. 各手のSVGを生成
  // Note: JSXで直接SVGを操作するため、dangerouslySetInnerHTMLを使用します。
const processSVG = (svgString: string, dotMap: Record<BrailleDot, string> | Record<LeftDot, string> | Record<RightDot, string>) => {
    let processedSVG = svgString;

    // 3. 各点（円）を処理してスタイルを適用
    for (const [dotNumStr, circleId] of Object.entries(dotMap)) {
      const dotNum = parseInt(dotNumStr) as BrailleDot;
      const isPressed = dotSet.has(dotNum);
      
      const fill = isPressed ? COLOR_MAP[dotNum] : 'none'; // 押されていれば色を、そうでなければ 'none' (透明)
      const stroke = isPressed ? 'none' : '#ccc';         // 押されていれば枠線を非表示、そうでなければ薄いグレーの枠線

      // SVG文字列を直接操作して、circle要素の属性を更新
      const circleRegex = new RegExp(`(<circle\\s+[^>]*?id=["']${circleId}["'][^>]*?)(\\s*\\/?>)`, 's');
      
      // fillとstroke属性を追加または置換（stroke-dasharray: r=32で、13個の波線になるような値にしている）
      const newCircleString = `$1 fill="${fill}" stroke="${stroke}" stroke-width="6" stroke-dasharray="7.73, 7.73"$2`;
      processedSVG = processedSVG.replace(circleRegex, newCircleString);
    }
    return processedSVG;
  };
  
  // 4. 左右の手のSVGをそれぞれ処理
  const leftSVG = processSVG(getLeftHandSVG(leftDots), LEFT_DOT_MAP);
  const rightSVG = processSVG(getRightHandSVG(rightDots), RIGHT_DOT_MAP);


  return (
    <div className="finger-braille-svg-container" style={{ display: 'flex', justifyContent: 'center', gap: '20px', width: '100%', height: '100%', objectFit: 'contain' }}>
      {/* 左手 */}
      <div 
        dangerouslySetInnerHTML={{ __html: leftSVG }} 
        style={{ width: '40%', maxWidth: '100px' }}
      />
      {/* 右手 */}
      <div 
        dangerouslySetInnerHTML={{ __html: rightSVG }} 
        style={{ width: '40%', maxWidth: '100px' }} 
      />
    </div>
  );
};

export default FingerBrailleSVG;